local function map(mode, key, action, desc)
	vim.keymap.set(mode, key, action, { desc = desc, silent = true })
end
map("n", "<leader>ff", function()
	MiniPick.builtin.files()
end, "Find files")
map("n", "<leader>fg", function()
	MiniPick.builtin.grep_live()
end, "Search project text")
map("n", "<leader>fb", function()
	MiniPick.builtin.buffers()
end, "Find buffers")
map("n", "<leader>fh", function()
	MiniPick.builtin.help()
end, "Search help")
map("n", "<leader>fd", function()
	MiniExtra.pickers.diagnostic()
end, "Find diagnostics")
map("n", "<leader>e", "<cmd>NvimTreeToggle<cr>", "Toggle file sidebar")
map("n", "<leader>w", "<cmd>write<cr>", "Save")
map("n", "<leader>q", "<cmd>quit<cr>", "Quit window")
map("n", "<leader>bd", "<cmd>bdelete<cr>", "Close buffer")
map("n", "<S-h>", "<cmd>bprevious<cr>", "Previous buffer")
map("n", "<S-l>", "<cmd>bnext<cr>", "Next buffer")
map({ "n", "v" }, "<leader>cf", function()
	require("conform").format({ lsp_format = "fallback" })
end, "Format")
map("n", "<leader>ut", function()
	require("config.theme").toggle()
end, "Toggle light / dark theme")
map("n", "<leader>vc", function()
	vim.cmd.edit(vim.fn.stdpath("config") .. "/init.lua")
end, "Edit Neovim config")
map("n", "<leader>tt", function()
	vim.cmd("botright 12split")
	vim.cmd.terminal({ "/bin/zsh", "--login" })
	vim.cmd.startinsert()
end, "Open bottom terminal")
map("t", "<Esc><Esc>", "<C-\\><C-n>", "Leave terminal mode")
map("n", "<Esc>", "<cmd>nohlsearch<cr>", "Clear search highlight")
for _, key in ipairs({ "h", "j", "k", "l" }) do
	map("n", "<C-" .. key .. ">", "<C-w>" .. key, "Focus adjacent window")
end
